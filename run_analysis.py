"""
Run every SQL file in sql/ against retail.db, in order.

  -- @script <name> ... -- @end   blocks are executed as DDL (building tables)
  -- @query <id>: <title>         blocks are executed as queries; results are
                                  saved to results/<id>.csv and results/RESULTS.md

Charts built from the query results are saved to images/.

Usage:  python load_data.py   (once)  then  python run_analysis.py
"""
import re
import sqlite3
import time
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import matplotlib.ticker as mtick
import pandas as pd

DB_FILE = Path("retail.db")
SQL_DIR, OUT_DIR, IMG_DIR = Path("sql"), Path("results"), Path("images")
MARKER = re.compile(r"^-- @(query|script|end)\b(.*)$", re.MULTILINE)

plt.style.use("seaborn-v0_8-whitegrid")
plt.rcParams.update({"figure.dpi": 110, "axes.titleweight": "bold"})
GBP = mtick.FuncFormatter(lambda x, _: f"£{x / 1e6:.1f}M" if x >= 1e6 else f"£{x / 1e3:,.0f}k")


def parse_blocks(sql_text: str):
    """Split a .sql file into (kind, name, title, sql) blocks using the @ markers."""
    marks = list(MARKER.finditer(sql_text))
    for m, nxt in zip(marks, marks[1:] + [None]):
        kind, rest = m.group(1), m.group(2).strip()
        if kind == "end":
            continue
        body = sql_text[m.end(): nxt.start() if nxt else len(sql_text)].strip()
        name, _, title = rest.partition(":")
        yield kind, name.strip(), title.strip(), body


def fmt(value, column: str) -> str:
    if pd.isna(value):
        return ""
    if column.endswith(("_id", "_code", "_month", "_day")) or column in ("rank", "hour_of_day", "month_number"):
        return str(int(value)) if isinstance(value, float) else str(value)   # identifiers: no separators
    if isinstance(value, float):
        return f"{value:,.0f}" if value.is_integer() else f"{value:,.2f}".rstrip("0").rstrip(".")
    return f"{value:,}" if isinstance(value, int) else str(value)


def to_markdown(df: pd.DataFrame, max_rows: int = 25) -> str:
    df = df.head(max_rows)
    rows = [" | ".join(df.columns), " | ".join("---" for _ in df.columns)]
    rows += [" | ".join(fmt(v, c) for v, c in zip(r, df.columns)) for r in df.itertuples(index=False)]
    return "\n".join(f"| {r} |" for r in rows)


def run_all(con) -> dict:
    results, md = {}, ["# Query results", "",
                       "Generated by `run_analysis.py` from the SQL files in `sql/`. Long tables show the first 25 rows.", ""]
    for path in sorted(SQL_DIR.glob("*.sql")):
        md += [f"## {path.name}", ""]
        for kind, name, title, body in parse_blocks(path.read_text(encoding="utf-8")):
            start = time.time()
            if kind == "script":
                con.executescript(body)
                print(f"  built model ({name}) in {time.time() - start:.1f}s")
                continue
            df = pd.read_sql_query(body, con)
            results[name] = df
            df.to_csv(OUT_DIR / f"{name}.csv", index=False)
            md += [f"### {name}: {title}", "", to_markdown(df), ""]
            print(f"  {name:<28} {len(df):>4} rows  {time.time() - start:5.1f}s")
    (OUT_DIR / "RESULTS.md").write_text("\n".join(md), encoding="utf-8")
    return results


def charts(r: dict, con) -> None:
    # 1. Monthly revenue trend
    m = r["05_monthly_trend"]
    fig, ax = plt.subplots(figsize=(11, 4))
    ax.bar(m.order_month, m.revenue, color="#4C72B0")
    ax.yaxis.set_major_formatter(GBP)
    ax.set_xticks(range(0, len(m), 2), m.order_month[::2], rotation=45, ha="right")
    ax.set_title("Monthly revenue, Dec 2009 – Nov 2011")
    fig.tight_layout(); fig.savefig(IMG_DIR / "monthly_revenue.png"); plt.close(fig)

    # 2. RFM segments: share of customers vs share of revenue
    s = r["13_rfm_segments"].set_index("segment")[["pct_of_customers", "pct_of_revenue"]]
    ax = s.plot(kind="barh", figsize=(9, 4.2), color=["#9DB4D3", "#1F3864"])
    ax.invert_yaxis(); ax.set_xlabel("%"); ax.set_ylabel("")
    ax.legend(["% of customers", "% of revenue"], loc="lower right")
    ax.set_title("RFM segments: share of customers vs share of revenue")
    plt.tight_layout(); plt.savefig(IMG_DIR / "rfm_segments.png"); plt.close()

    # 3. Cohort retention heatmap
    c = r["15_cohort_retention"].set_index("cohort_month")[["m1", "m2", "m3", "m6", "m9", "m12"]]
    fig, ax = plt.subplots(figsize=(8, 8))
    im = ax.imshow(c.values, cmap="Blues", aspect="auto", vmin=0, vmax=50)
    ax.set_xticks(range(c.shape[1]), ["Month 1", "Month 2", "Month 3", "Month 6", "Month 9", "Month 12"])
    ax.set_yticks(range(c.shape[0]), c.index)
    for i in range(c.shape[0]):
        for j in range(c.shape[1]):
            v = c.values[i, j]
            if pd.notna(v) and v > 0:
                ax.text(j, i, f"{v:.0f}%", ha="center", va="center", fontsize=8, color="white" if v > 30 else "black")
    ax.grid(False); ax.set_title("Cohort retention: % of customers ordering again")
    fig.colorbar(im, ax=ax, fraction=0.04, label="% retained")
    fig.tight_layout(); fig.savefig(IMG_DIR / "cohort_retention.png"); plt.close(fig)

    # 4. Pareto curve of product revenue
    p = pd.read_sql_query("SELECT net_revenue FROM products WHERE net_revenue > 0 ORDER BY net_revenue DESC", con)
    cum = p.net_revenue.cumsum() / p.net_revenue.sum() * 100
    x = (pd.Series(range(1, len(p) + 1)) / len(p)) * 100
    k80 = int((cum >= 80).idxmax())
    fig, ax = plt.subplots(figsize=(8, 4.2))
    ax.plot(x, cum, lw=2, color="#1F3864")
    ax.axhline(80, ls="--", color="grey", lw=1); ax.axvline(x[k80], ls="--", color="grey", lw=1)
    ax.annotate(f"{x[k80]:.0f}% of products\n= 80% of revenue", (x[k80], 80), xytext=(x[k80] + 8, 55),
                arrowprops={"arrowstyle": "->"})
    ax.set_xlabel("% of products (ranked by revenue)"); ax.set_ylabel("% of revenue (cumulative)")
    ax.set_title("Pareto curve: product net revenue concentration")
    fig.tight_layout(); fig.savefig(IMG_DIR / "pareto_products.png"); plt.close(fig)
    print("  charts saved to images/")


def main() -> None:
    OUT_DIR.mkdir(exist_ok=True); IMG_DIR.mkdir(exist_ok=True)
    with sqlite3.connect(DB_FILE) as con:
        con.execute("PRAGMA temp_store = MEMORY")
        print("Running SQL files...")
        results = run_all(con)
        charts(results, con)
    print("Done. See results/RESULTS.md")


if __name__ == "__main__":
    main()
